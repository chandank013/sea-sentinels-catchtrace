// Helper to compute user trust score dynamically from actual batch events
export function computeUserTrustScore(user, batches = BATCHES) {
  if (!user) return { trust_score: 100, confirmed_count: 0, disputed_count: 0 };

  const userId = (user.id || '').toLowerCase().trim();
  const userName = (user.name || '').toLowerCase().trim();
  const userOrg = (user.org || '').toLowerCase().trim();

  let confirmed = 0;
  let disputed = 0;

  if (Array.isArray(batches)) {
    batches.forEach((b) => {
      (b.events || []).forEach((e) => {
        const matchActor =
          (e.actor_id && userId && e.actor_id.toLowerCase().trim() === userId) ||
          (e.actor_name && userName && e.actor_name.toLowerCase().includes(userName)) ||
          (e.org_name && userOrg && (userOrg.includes(e.org_name.toLowerCase()) || e.org_name.toLowerCase().includes(userOrg)));

        if (matchActor) {
          if (e.confirmation_status === 'CONFIRMED') confirmed++;
          else if (e.confirmation_status === 'DISPUTED') disputed++;
        }
      });
    });
  }

  // Fallback to user seed counts if no batch events found
  if (confirmed === 0 && disputed === 0 && (user.confirmed_count || user.disputed_count)) {
    confirmed = user.confirmed_count || 0;
    disputed = user.disputed_count || 0;
  }

  const total = confirmed + disputed;
  const trust_score = total === 0 ? 100 : Math.round((confirmed / total) * 100);

  return {
    trust_score,
    confirmed_count: confirmed,
    disputed_count: disputed,
  };
}

